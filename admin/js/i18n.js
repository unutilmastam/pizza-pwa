let currentLang = ADMIN.defaultLang;

/**
 * Saqlangan tilni tiklaydi.
 * @returns {string}
 */
export function initLang() {
  try {
    const saved = localStorage.getItem(ADMIN.storage.lang);
    if (saved && DICT[saved]) currentLang = saved;
  } catch (e) {
    // Shaxsiy rejimda localStorage yopiq bo'lishi mumkin — standart til qoladi
  }
  document.documentElement.lang = currentLang;
  return currentLang;
}

/**
 * Tilni almashtiradi.
 * @param {string} lang
 */
export function setLang(lang) {
  if (!DICT[lang]) return;
  currentLang = lang;
  document.documentElement.lang = lang;
  try {
    localStorage.setItem(ADMIN.storage.lang, lang);
  } catch (e) {
    // Saqlanmasa ham joriy seansda til ishlaydi
  }
}

/** @returns {string} */
export function getLang() {
  return currentLang;
}

/**
 * Kalit bo'yicha matn. `{vars}` o'rniga qiymat qo'yiladi.
 * @param {string} key
 * @param {object} [vars]
 * @returns {string}
 */
export function t(key, vars = {}) {
  const text = (DICT[currentLang] && DICT[currentLang][key]) ||
    DICT[ADMIN.defaultLang][key] || key;
  return text.replace(/\{(\w+)\}/g, (m, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : m);
}
